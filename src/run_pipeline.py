"""End-to-end pipeline: warehouse -> SQL views -> fair-lending statistics -> figures -> Excel, Power BI, docs.

Usage:
    python -m src.run_pipeline                  # full run
    python -m src.run_pipeline --analysis-only  # skip Excel, Power BI and README rendering
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

import numpy as np
import pandas as pd

from src import config, data, fairlending, figures


def records(df: pd.DataFrame) -> list[dict]:
    out = []
    for rec in df.to_dict(orient="records"):
        clean = {}
        for k, v in rec.items():
            if isinstance(v, (np.floating, float)):
                clean[k] = None if np.isnan(v) else float(v)
            elif isinstance(v, np.integer):
                clean[k] = int(v)
            elif isinstance(v, np.bool_):
                clean[k] = bool(v)
            else:
                clean[k] = v
        out.append(clean)
    return out


def write_quality_log(checks: pd.DataFrame, counts: dict) -> None:
    lines = ["# Data quality log", "",
             "Generated by `src/run_pipeline.py` from `sql/03_quality_checks.sql`. Hard rules stop the pipeline; "
             "soft rules are expected properties of HMDA data and are handled as described in "
             "`docs/methodology.md`.", "", "| Rule | Severity | Rows | Status |", "|---|---|---:|---|"]
    for r in checks.itertuples():
        status = "pass" if r.failures == 0 else ("FAIL" if r.severity == "hard" else "noted")
        lines.append(f"| {r.rule} | {r.severity} | {int(r.failures):,} | {status} |")
    lines += ["", "## Row counts", "", "| Table or view | Rows |", "|---|---:|"]
    lines += [f"| {k} | {v:,} |" for k, v in counts.items()]
    (config.ROOT / "docs" / "data_quality_log.md").write_text("\n".join(lines) + "\n")


def main(analysis_only: bool = False) -> dict:
    for folder in (config.FIGURES, config.TABLES, config.POWERBI_DATA):
        folder.mkdir(parents=True, exist_ok=True)
    checks = data.build_warehouse()
    counts = data.row_counts()
    write_quality_log(checks, counts)
    print("warehouse built", counts, flush=True)

    funnel = data.query("04_funnel.sql")
    rates = data.query("05_group_rates.sql")
    dti = data.query("06_dti_profile.sql")
    reasons = data.query("07_denial_reasons.sql")
    lender_bench = data.query("08_lenders.sql")
    states = data.query("09_states.sql")
    counties = data.query("10_counties.sql")
    tracts = data.query("11_tracts.sql")
    cube = data.query("12_powerbi_cube.sql")
    grid = data.query("13_policy_grid.sql")
    income_tract = data.query("14_income_tract.sql")
    lenders = data.query("SELECT * FROM lenders")
    gr = fairlending.group_rates(rates)

    # ---- statistics on applications with every underwriting control
    df = data.model_frame()
    core_n = counts["core"]
    excluded = data.query("""SELECT applicant_group, COUNT(*) AS applications, AVG(denied) AS denial_rate
                             FROM core WHERE app_id NOT IN (SELECT app_id FROM model_frame)
                               AND applicant_group IN ('White', 'Black', 'Hispanic', 'Asian', 'Other minority')
                             GROUP BY 1 ORDER BY 2 DESC""")
    ladder, ladder_fits = fairlending.gap_ladder(df)
    logit = fairlending.logit_check(df)
    print("logit check done", flush=True)
    oax = fairlending.decompositions(df)
    price, price_stats = fairlending.pricing(df)
    hood = fairlending.neighbourhood(df)
    screen = fairlending.lender_screen(df, lenders)
    print(f"lender screen done ({len(screen)} lenders)", flush=True)

    # ---- derived headline numbers
    total = funnel[funnel.loan_type == "All"].iloc[0]
    dti_conv = dti[dti.loan_type == "Conventional"].set_index("dti_value")
    dti_fha = dti[dti.loan_type == "FHA"].set_index("dti_value")
    cliff = {"conventional_at_49": float(dti_conv.loc[49, "denial_rate"]),
             "conventional_50_60": float(dti_conv.loc[55, "denial_rate"]),
             "conventional_over_60": float(dti_conv.loc[65, "denial_rate"]),
             "conventional_36_to_49_mean": float(np.average(dti_conv.loc[36:49, "denial_rate"],
                                                            weights=dti_conv.loc[36:49, "applications"])),
             "fha_at_49": float(dti_fha.loc[49, "denial_rate"]), "fha_50_60": float(dti_fha.loc[55, "denial_rate"]),
             "conventional_50_60_share_citing_dti": float(dti_conv.loc[55, "share_of_denials_citing_dti"]),
             "conventional_apps_50_plus": int(dti_conv.loc[[55, 65], "applications"].sum())}
    reason_piv = reasons.pivot(index="reason", columns="applicant_group", values="share_of_denials")
    spec2 = ladder[ladder.spec.str.startswith("2")].set_index("group")
    spec4 = ladder[ladder.spec.str.startswith("4")].set_index("group")
    raw = ladder[ladder.spec.str.startswith("1")].set_index("group")
    pspec3 = price[price.spec.str.startswith("3")].set_index("group")
    n_black = int((screen.ci_low_black > 0).sum()) if len(screen) else 0
    n_hisp = int((screen.ci_low_hispanic > 0).sum()) if len(screen) else 0
    top_lenders = lender_bench.head(10)
    scenarios = []
    for name, dmax, lmax in (("DTI cap 44%", 5, 7), ("DTI cap 49%", 6, 7), ("LTV cap 95%", 9, 4),
                             ("DTI cap 44% and LTV cap 95%", 5, 4)):
        sim = fairlending.simulate_policy(grid, dmax, lmax)
        scenarios.append(sim.assign(scenario=name))
    scen = pd.concat(scenarios, ignore_index=True)

    tables = {"quality_checks": checks, "funnel_by_loan_type": funnel, "rates_by_group": gr,
              "rates_by_group_and_loan_type": rates[rates.loan_type != "All"], "denial_by_dti": dti,
              "denial_reasons": reasons, "lender_benchmark_top_200": lender_bench.head(200), "states": states,
              "counties": counties, "tracts": tracts, "denial_gap_ladder": ladder, "logit_marginal_effects": logit,
              "pricing_gaps": price, "neighbourhood_gaps": hood, "lender_screen": screen, "policy_grid": grid,
              "model_frame_exclusions": excluded, "policy_scenarios": scen,
              "oaxaca_blinder": pd.DataFrame([{k: v for k, v in o.items() if k != "blocks"} | o["blocks"] for o in oax])}
    for name, t in tables.items():
        t.to_csv(config.TABLES / f"{name}.csv", index=False)

    figs = [figures.denial_by_group(gr), figures.gap_ladder(ladder), figures.dti_profile(dti),
            figures.denial_reasons(reasons), figures.decomposition(oax), figures.tract_heatmap(tracts),
            figures.pricing_gaps(price)]
    if len(screen):
        figs.append(figures.lender_screen(screen))

    results = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "settings": {"year": config.YEAR, "reference_group": config.REFERENCE_GROUP, "groups": config.GROUPS,
                     "min_lender_apps": config.MIN_LENDER_APPS, "min_lender_group_apps": config.MIN_LENDER_GROUP_APPS,
                     "logit_sample": config.LOGIT_SAMPLE, "four_fifths": config.FOUR_FIFTHS, "seed": config.SEED},
        "row_counts": counts,
        "quality": {"hard_checks_passed": True, "rules": int(len(checks)),
                    "soft_findings": records(checks[(checks.severity == "soft") & (checks.failures > 0)])},
        "business": {"all_applications": counts["applications"], "core_applications": core_n,
                     "core_share": core_n / counts["applications"], "approved": int(total.approved),
                     "denied": int(total.denied), "originated": int(total.originated),
                     "denial_rate": float(total.denial_rate), "originated_volume": float(total.originated_volume),
                     "median_loan_amount": float(total.median_loan_amount),
                     "median_income_k": float(total.median_income_k), "lenders": int(lender_bench.lei.nunique()),
                     "by_loan_type": records(funnel[funnel.loan_type != "All"]),
                     "top_lenders": records(top_lenders[["lender_name", "applications", "denial_rate",
                                                         "originated_volume"]])},
        "groups": {"rates": records(gr),
                   "any_below_four_fifths": bool(gr[gr.applicant_group.isin(config.GROUPS)].below_four_fifths.any())},
        "dti_cliff": cliff,
        "denial_reasons": {"credit_history": {g: float(reason_piv.loc["Credit history", g]) for g in reason_piv.columns},
                           "dti": {g: float(reason_piv.loc["Debt-to-income ratio", g]) for g in reason_piv.columns},
                           "collateral": {g: float(reason_piv.loc["Collateral", g]) for g in reason_piv.columns}},
        "model_frame": {"applications": int(len(df)), "share_of_core": len(df) / core_n,
                        "denial_rate": float(df.denied.mean()), "exclusions": records(excluded)},
        "gap_ladder": {"rows": records(ladder), "fits": ladder_fits,
                       "share_explained_by_controls": {g: float(1 - spec2.loc[g, "coef"] / raw.loc[g, "coef"])
                                                       for g in spec2.index},
                       "share_explained_with_lender_county": {g: float(1 - spec4.loc[g, "coef"] / raw.loc[g, "coef"])
                                                              for g in spec4.index}},
        "logit": records(logit),
        "oaxaca": oax,
        "pricing": {"rows": records(price), **price_stats,
                    "lender_state_gap_bps": {g: float(pspec3.loc[g, "coef"]) for g in pspec3.index},
                    "lender_state_ci_bps": {g: [float(pspec3.loc[g, "ci_low"]), float(pspec3.loc[g, "ci_high"])]
                                            for g in pspec3.index}},
        "neighbourhood": records(hood),
        "lender_screen": {"lenders": int(len(screen)), "black_gap_above_zero": n_black,
                          "hispanic_gap_above_zero": n_hisp,
                          "median_adj_gap_black": float(screen.adj_gap_black.median()) if len(screen) else None,
                          "median_adj_gap_hispanic": float(screen.adj_gap_hispanic.median()) if len(screen) else None,
                          "rows": records(screen)},
        "policy_scenarios": {name: {"total_approvals_lost": int(d.approvals_lost.sum()),
                                    "total_share_lost": float(d.approvals_lost.sum() / d.approved.sum()),
                                    "volume_lost": float(d.volume_lost.sum()), "by_group": records(d)}
                             for name, d in scen.groupby("scenario", sort=False)},
        "figures": figs,
    }
    config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))

    if not analysis_only:
        from src import excel_model, powerbi, report
        results["powerbi"] = powerbi.export(cube, income_tract, dti, reasons, ladder, price, screen, counties)
        results["excel"] = excel_model.build(results, grid, ladder, screen)
        report.render(results)
        config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))
    b = results["gap_ladder"]["rows"]
    print("Pipeline finished: Black-White denial gap "
          + ", ".join(f"{r['spec']}: {r['coef'] * 100:.1f} pp" for r in b if r["group"] == "Black"))
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis-only", action="store_true")
    main(analysis_only=parser.parse_args().analysis_only)
